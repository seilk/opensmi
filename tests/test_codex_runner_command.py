import platform
import subprocess
import sys
import unittest


class CodexRunnerCommandOutput(unittest.TestCase):
    def test_command_output(self):
        if platform.system() != "Linux" or sys.version_info[:2] != (3, 10):
            self.skipTest("temporary command-output check only runs on linux py3.10")

        command = "echo SEILK_RUNNER_TEST_OK; hostname; uname -a; python3 --version"
        result = subprocess.run(
            command,
            shell=True,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
        )

        self.fail("\n===== command output =====\n" + result.stdout)
